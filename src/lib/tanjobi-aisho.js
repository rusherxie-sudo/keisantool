// あなたのタイプから見た、相手の生まれ年の配置。{ zone, category, score, comment } または null。
export function rokuseiAisho(type, partnerBirthYear) {
  const z = fortuneZone(type, partnerBirthYear);
  if (!z) return null;
  const a = zoneAisho(z.zone);
  return { zone: z.zone, category: z.category, score: a.score, comment: a.comment };
}

// 総合ランク帯: ◎85以上／○70〜84／△55〜69／▲55未満。
function rankOf(score) {
  return score >= 85 ? '◎' : score >= 70 ? '○' : score >= 55 ? '△' : '▲';
}

// ふたりの生年月日から総合判定。person は { y, m, d }。不正な日付は null。
export function tanjobiAisho(person1, person2) {
  const b1 = birthNumber(person1.y, person1.m, person1.d);
  const b2 = birthNumber(person2.y, person2.m, person2.d);
  if (!b1 || !b2) return null;
  const r1 = rokusei(person1.y, person1.m, person1.d);
  const r2 = rokusei(person2.y, person2.m, person2.d);
  const suuhi = suuhiAisho(b1.number, b2.number);
  const a2b = rokuseiAisho(r1.type, person2.y);
  const b2a = rokuseiAisho(r2.type, person1.y);
  const rokuseiScore = Math.floor((a2b.score + b2a.score) / 2);
  const totalScore = Math.floor((suuhi.score + rokuseiScore) / 2);
  const totalRank = rankOf(totalScore);
  return {
    p1: { birth: b1, rokusei: r1 },
    p2: { birth: b2, rokusei: r2 },
    suuhi,
    rokusei: { a2b, b2a, score: rokuseiScore },
    total: { score: totalScore, rank: totalRank, label: RANK_LABELS[totalRank] },
  };
}

