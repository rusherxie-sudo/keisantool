// 実在する日付かどうか（rokusei.js と同基準・UTC正午不要の整数判定）。
function validDate(y, m, d) {
  if (![y, m, d].every((v) => Number.isInteger(v))) return false;
  if (m < 1 || m > 12 || d < 1 || d > 31) return false;
  const dt = new Date(Date.UTC(y, m - 1, d));
  return (
    dt.getUTCFullYear() === y && dt.getUTCMonth() === m - 1 && dt.getUTCDate() === d
  );
}

const MASTERS = new Set([11, 22, 33]);
const MASTER_BASE = { 11: 2, 22: 4, 33: 6 };

// 数字の各桁を足す。
function digitSum(n) {
  return String(n)
    .split('')
    .reduce((acc, c) => acc + Number(c), 0);
}

// 誕生数（ライフパスナンバー）。{ number, isMaster, base } または null。
export function birthNumber(y, m, d) {
  if (!validDate(y, m, d)) return null;
  const digits = `${String(y).padStart(4, '0')}${String(m).padStart(2, '0')}${String(d).padStart(2, '0')}`;
  let total = digitSum(digits);
  while (total > 9 && !MASTERS.has(total)) {
    total = digitSum(total);
  }
  const isMaster = MASTERS.has(total);
  return {
    number: total,
    isMaster,
    base: isMaster ? MASTER_BASE[total] : total,
  };
}

