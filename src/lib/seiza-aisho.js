const INDEX = new Map(SIGNS.map((s, i) => [s.slug, i]));

// slug から星座データを引く。無効なら null。
export function signBySlug(slug) {
  const i = INDEX.get(slug);
  return i === undefined ? null : SIGNS[i];
}

// 2星座の相性を判定する。無効な slug は null。
export function seizaAisho(slug1, slug2) {
  const i1 = INDEX.get(slug1);
  const i2 = INDEX.get(slug2);
  if (i1 === undefined || i2 === undefined) return null;
  const s1 = SIGNS[i1];
  const s2 = SIGNS[i2];
  const diff = Math.abs(i1 - i2);
  const distance = Math.min(diff, 12 - diff);
  const a = ASPECTS[distance];
  const fill = (t) => t.replaceAll('{el1}', s1.element).replaceAll('{el2}', s2.element);
  return {
    score: a.score,
    rank: a.rank,
    aspect: { distance, name: a.name },
    element1: s1.element,
    element2: s2.element,
    comment: fill(a.comment),
    advice: fill(a.advice),
  };
}

// 144組（同星座・両方向を含む）のページ生成用ペア一覧。
export function allPairs() {
  const pairs = [];
  for (const a of SIGNS) {
    for (const b of SIGNS) {
      pairs.push({ slug1: a.slug, slug2: b.slug });
    }
  }
  return pairs;
}
