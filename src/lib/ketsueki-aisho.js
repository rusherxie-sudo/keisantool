// キーを TYPES 順の無序対に正規化する。
function pairKey(t1, t2) {
  const i1 = TYPES.indexOf(t1);
  const i2 = TYPES.indexOf(t2);
  return i1 <= i2 ? `${t1}-${t2}` : `${t2}-${t1}`;
}

// ランク帯: ◎85以上／○70〜84／△70未満。
// 血液型は3段階のみ（最低のA×B=52も△）。「どの組み合わせにも良さがある」娯楽の趣旨で▲は使わない。
function rankOf(score) {
  return score >= 85 ? '◎' : score >= 70 ? '○' : '△';
}

// 血液型相性の判定。t1=あなた、t2=相手。無効な型は null。
export function ketsuekiAisho(t1, t2) {
  if (!TYPES.includes(t1) || !TYPES.includes(t2)) return null;
  const score = SCORES[pairKey(t1, t2)];
  return {
    score,
    rank: rankOf(score),
    comment: COMMENTS[`${t1}-${t2}`],
    advice: ADVICE[pairKey(t1, t2)],
  };
}

// 静的表示用: 無序対10組の一覧（TYPES 順）。
export function allCombos() {
  const combos = [];
  for (let i = 0; i < TYPES.length; i++) {
    for (let j = i; j < TYPES.length; j++) {
      combos.push({ t1: TYPES[i], t2: TYPES[j] });
    }
  }
  return combos;
}
